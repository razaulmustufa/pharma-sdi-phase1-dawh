"""Sales & Demand Intelligence (SDI) Phase 1 — idempotent Apache Airflow 3 DAG.

Local teaching/demo deployment using existing Airflow Compose PostgreSQL server,
but a SEPARATE database named sdi_phase1. This is not production architecture.

Prerequisites:
  1) docker compose exec postgres psql -U airflow -d postgres -c 'CREATE DATABASE sdi_phase1;'
  2) Put the three source CSV files in dags/data/
  3) Copy this file to dags/
  4) Trigger DAG 'sdi_phase1_etl' in Airflow.

For incremental refreshes, append genuinely new primary keys to the source CSVs,
then trigger again. This pipeline never TRUNCATEs the staging or fact tables.
"""

import csv
import logging
import os
import time
from pathlib import Path

import pendulum
from airflow.sdk import dag, task

DATA_DIR = Path("/opt/airflow/dags/data")
DB_CONF = {
    "host": os.getenv("SDI_DB_HOST", "postgres"),
    "port": int(os.getenv("SDI_DB_PORT", "5432")),
    "dbname": os.getenv("SDI_DB_NAME", "sdi_phase1"),
    "user": os.getenv("SDI_DB_USER", "airflow"),
    "password": os.getenv("SDI_DB_PASSWORD", "airflow"),
    "connect_timeout": 15,
}

SOURCES = {
    "01_master_data.csv": ("staging", "master_data", "MedicineID"),
    "05_pharmacy_sales_data.csv": ("staging", "pharmacy_sales", "SalesTransactionID"),
    "06_hospital_demand_data.csv": ("staging", "hospital_demand", "HospitalDemandRecordID"),
}


def connect_db():
    # Airflow Docker Compose image has PostgreSQL drivers for its metadata DB.
    import psycopg2
    return psycopg2.connect(**DB_CONF)


def norm(col):
    """SQL expression normalizing a location attribute for a conformed key."""
    return f"COALESCE(NULLIF(UPPER(BTRIM({col})), ''), 'UNKNOWN')"


def loc_expr(country, state, city):
    return f"{norm(country)} || '|' || {norm(state)} || '|' || {norm(city)}"


