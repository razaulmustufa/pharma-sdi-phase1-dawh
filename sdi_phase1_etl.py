def ingest(filename):
    """Stage a CSV using COPY, then insert only previously unseen natural keys.

    Uses a temporary table for idempotence; never clears historical rows.
    All staging columns preserve raw source values as TEXT.
    """
    from psycopg2 import sql

    t0 = time.perf_counter()
    if filename not in SOURCES:
        raise ValueError(f"Source not recognized: {filename}")
    schema, table, pk = SOURCES[filename]
    path = DATA_DIR / filename
    if not path.is_file():
        raise FileNotFoundError(f"Missing {path}")
    with path.open("r", newline="", encoding="utf-8-sig") as f:
        cols = csv.DictReader(f).fieldnames
    if not cols or pk not in cols:
        raise ValueError(f"{filename} missing header / primary key {pk}")
    if len(cols) != len(set(cols)):
        raise ValueError(f"{filename} contains duplicate column headers")

    with connect_db() as con:
        with con.cursor() as cur:
            target = sql.Identifier(schema, table)
            fields = sql.SQL(", ").join(sql.Identifier(c) for c in cols)
            definitions = sql.SQL(", ").join(
                sql.SQL("{} TEXT").format(sql.Identifier(c)) for c in cols
            )
            cur.execute(sql.SQL("CREATE TABLE IF NOT EXISTS {} ({}, PRIMARY KEY ({}))").format(
                target, definitions, sql.Identifier(pk)))
            cur.execute(sql.SQL("CREATE TEMP TABLE temp_ingest (LIKE {} INCLUDING DEFAULTS) ON COMMIT DROP").format(target))
            copy_command = sql.SQL("COPY temp_ingest ({}) FROM STDIN WITH (FORMAT csv, HEADER TRUE)").format(fields).as_string(con)
            with path.open("r", encoding="utf-8-sig", newline="") as infile:
                cur.copy_expert(copy_command, infile)
            cur.execute("SELECT COUNT(*) FROM temp_ingest")
            scanned = cur.fetchone()[0]
            cur.execute(sql.SQL("SELECT COUNT(*) FROM temp_ingest WHERE NULLIF(BTRIM({}), '') IS NULL").format(sql.Identifier(pk)))
            blanks = cur.fetchone()[0]
            if blanks:
                raise ValueError(f"{filename}: {blanks} blank primary keys, aborting load")
            # PostgreSQL ON CONFLICT DO NOTHING skips existing and repeated keys.
            # WHERE TRUE avoids a PostgreSQL parser ambiguity.
            cur.execute(sql.SQL("""
                INSERT INTO {} ({})
                SELECT {} FROM temp_ingest WHERE TRUE
                ON CONFLICT ({}) DO NOTHING
            """).format(target, fields, fields, sql.Identifier(pk)))
            added = cur.rowcount
            elapsed = round(time.perf_counter() - t0, 3)
            cur.execute("""INSERT INTO ops.batch_load_log
                (source_name, elapsed_seconds, scanned_rows, newly_inserted_rows, status)
                VALUES (%s, %s, %s, %s, 'success')""",
                (filename, elapsed, scanned, added))
    logging.info("STAGED %s: scanned=%s, newly inserted=%s, duration=%.3fs", filename, scanned, added, elapsed)
    return {"file": filename, "scanned": scanned, "inserted": added, "seconds": elapsed}


def build_dimensions():
    sales_location = loc_expr('"CountryCode"', '"PharmacyState"', '"PharmacyCity"')
    demand_location = loc_expr('"CountryCode"', '"State"', '"City"')
    statements = [
        # Every date is a true calendar key; hospital demand uses month start.
        """INSERT INTO mart.dim_date (date_key, full_date, year_number, quarter_number, month_number, month_name, day_of_month)
        SELECT TO_CHAR(d, 'YYYYMMDD')::INTEGER, d, EXTRACT(YEAR FROM d)::INTEGER,
               EXTRACT(QUARTER FROM d)::INTEGER, EXTRACT(MONTH FROM d)::INTEGER,
               TO_CHAR(d, 'Mon'), EXTRACT(DAY FROM d)::INTEGER
        FROM (SELECT DISTINCT "SalesDate"::DATE AS d FROM staging.pharmacy_sales
              UNION SELECT DISTINCT "DemandMonth"::DATE AS d FROM staging.hospital_demand) dates
        WHERE d IS NOT NULL ON CONFLICT (date_key) DO NOTHING""",
        """INSERT INTO mart.dim_medicine
        (medicine_id, internal_sku, generic_name, disease_category, therapeutic_class,
         cold_chain_flag, storage_min_temp_c, storage_max_temp_c)
        SELECT "MedicineID", "InternalSKU", "GenericName", "DiseaseCategory", "TherapeuticClass",
               "ColdChainFlag", NULLIF("StorageMinTempC", '')::NUMERIC,
               NULLIF("StorageMaxTempC", '')::NUMERIC
        FROM staging.master_data WHERE TRUE
        ON CONFLICT (medicine_id) DO UPDATE SET
          internal_sku=EXCLUDED.internal_sku, generic_name=EXCLUDED.generic_name,
          disease_category=EXCLUDED.disease_category, therapeutic_class=EXCLUDED.therapeutic_class,
          cold_chain_flag=EXCLUDED.cold_chain_flag,
          storage_min_temp_c=EXCLUDED.storage_min_temp_c,
          storage_max_temp_c=EXCLUDED.storage_max_temp_c""",
        f"""INSERT INTO mart.dim_location(natural_location_key, city, state, country_code)
        SELECT DISTINCT natural_location_key, city, state, country_code
        FROM (
            SELECT {sales_location} AS natural_location_key,
                {norm('"PharmacyCity"')} AS city, {norm('"PharmacyState"')} AS state,
                {norm('"CountryCode"')} AS country_code FROM staging.pharmacy_sales
            UNION
            SELECT {demand_location} AS natural_location_key,
                {norm('"City"')} AS city, {norm('"State"')} AS state,
                {norm('"CountryCode"')} AS country_code FROM staging.hospital_demand
        ) locations WHERE TRUE ON CONFLICT (natural_location_key) DO NOTHING""",
        """INSERT INTO mart.dim_channel(sales_channel)
        SELECT DISTINCT "SalesChannel" FROM staging.pharmacy_sales
        WHERE NULLIF(BTRIM("SalesChannel"),'') IS NOT NULL
        ON CONFLICT (sales_channel) DO NOTHING""",
        f"""INSERT INTO mart.dim_pharmacy(pharmacy_id, pharmacy_name, pharmacy_type, location_key)
        SELECT s."PharmacyID", s."PharmacyName", s."PharmacyType", l.location_key
        FROM (SELECT DISTINCT ON ("PharmacyID") * FROM staging.pharmacy_sales
              ORDER BY "PharmacyID", "SalesDate" DESC, "SalesTransactionID" DESC) s
        JOIN mart.dim_location l ON l.natural_location_key = {loc_expr('s."CountryCode"','s."PharmacyState"','s."PharmacyCity"')}
        WHERE TRUE ON CONFLICT (pharmacy_id) DO UPDATE SET
          pharmacy_name=EXCLUDED.pharmacy_name,
          pharmacy_type=EXCLUDED.pharmacy_type,
          location_key=EXCLUDED.location_key""",
        f"""INSERT INTO mart.dim_hospital(hospital_id, hospital_name, hospital_type, licensed_beds, location_key)
        SELECT s."HospitalID", s."HospitalName", s."HospitalType",
               NULLIF(s."LicensedBeds", '')::INTEGER, l.location_key
        FROM (SELECT DISTINCT ON ("HospitalID") * FROM staging.hospital_demand
              ORDER BY "HospitalID", "DemandMonth" DESC, "HospitalDemandRecordID" DESC) s
        JOIN mart.dim_location l ON l.natural_location_key = {loc_expr('s."CountryCode"','s."State"','s."City"')}
        WHERE TRUE ON CONFLICT (hospital_id) DO UPDATE SET
          hospital_name=EXCLUDED.hospital_name,
          hospital_type=EXCLUDED.hospital_type,
          licensed_beds=EXCLUDED.licensed_beds,
          location_key=EXCLUDED.location_key""",
    ]
    with connect_db() as con:
        with con.cursor() as cur:
            for stmt in statements:
                cur.execute(stmt)
            for table in ("dim_date", "dim_medicine", "dim_location", "dim_pharmacy", "dim_hospital", "dim_channel"):
                cur.execute(f"SELECT COUNT(*) FROM mart.{table}")
                logging.info("DIMENSION %s = %s rows", table, cur.fetchone()[0])
    return "six dimensions populated"


def build_facts():
    sales_loc = loc_expr('s."CountryCode"','s."PharmacyState"','s."PharmacyCity"')
    demand_loc = loc_expr('d."CountryCode"','d."State"','d."City"')
    sales_sql = f"""
        INSERT INTO mart.fact_sales (
          sales_transaction_id, date_key, medicine_key, location_key, pharmacy_key, channel_key,
          quantity_sold_packs, gross_sales_usd, discount_usd, net_sales_usd, cogs_usd,
          gross_margin_usd, returned_quantity_packs, sale_status)
        SELECT s."SalesTransactionID", TO_CHAR(s."SalesDate"::DATE,'YYYYMMDD')::INTEGER,
          m.medicine_key, l.location_key, p.pharmacy_key, c.channel_key,
          NULLIF(s."QuantitySoldPacks",'')::NUMERIC,
          NULLIF(s."GrossSalesAmountUSD",'')::NUMERIC,
          NULLIF(s."DiscountAmountUSD",'')::NUMERIC,
          NULLIF(s."NetSalesAmountUSD",'')::NUMERIC,
          NULLIF(s."CostOfGoodsSoldUSD",'')::NUMERIC,
          NULLIF(s."GrossMarginUSD",'')::NUMERIC,
          NULLIF(s."ReturnedQuantityPacks",'')::NUMERIC, s."SaleStatus"
        FROM staging.pharmacy_sales s
        JOIN mart.dim_medicine m ON m.medicine_id=s."MedicineID"
        JOIN mart.dim_location l ON l.natural_location_key={sales_loc}
        JOIN mart.dim_pharmacy p ON p.pharmacy_id=s."PharmacyID"
        JOIN mart.dim_channel c ON c.sales_channel=s."SalesChannel"
        WHERE TRUE ON CONFLICT (sales_transaction_id) DO NOTHING
    """
    demand_sql = f"""
        INSERT INTO mart.fact_demand (
          hospital_demand_record_id, date_key, medicine_key, location_key, hospital_key,
          forecast_demand_packs, requested_quantity_packs, received_quantity_packs,
          consumed_quantity_packs, unfulfilled_demand_packs, stockout_days)
        SELECT d."HospitalDemandRecordID", TO_CHAR(d."DemandMonth"::DATE,'YYYYMMDD')::INTEGER,
          m.medicine_key, l.location_key, h.hospital_key,
          NULLIF(d."ForecastDemandPacks",'')::NUMERIC,
          NULLIF(d."RequestedQuantityPacks",'')::NUMERIC,
          NULLIF(d."ReceivedQuantityPacks",'')::NUMERIC,
          NULLIF(d."ConsumedQuantityPacks",'')::NUMERIC,
          NULLIF(d."UnfulfilledDemandPacks",'')::NUMERIC,
          NULLIF(d."StockoutDays",'')::INTEGER
        FROM staging.hospital_demand d
        JOIN mart.dim_medicine m ON m.medicine_id=d."MedicineID"
        JOIN mart.dim_location l ON l.natural_location_key={demand_loc}
        JOIN mart.dim_hospital h ON h.hospital_id=d."HospitalID"
        WHERE TRUE ON CONFLICT (hospital_demand_record_id) DO NOTHING
    """
    with connect_db() as con:
        with con.cursor() as cur:
            cur.execute(sales_sql)
            inserted_sales = cur.rowcount
            cur.execute(demand_sql)
            inserted_demand = cur.rowcount
            cur.execute('SELECT COUNT(*) FROM mart.fact_sales')
            sales_count = cur.fetchone()[0]
            cur.execute('SELECT COUNT(*) FROM mart.fact_demand')
            demand_count = cur.fetchone()[0]
            cur.execute('SELECT COUNT(*) FROM staging.pharmacy_sales')
            raw_sales = cur.fetchone()[0]
            cur.execute('SELECT COUNT(*) FROM staging.hospital_demand')
            raw_demand = cur.fetchone()[0]
            # Full join coverage: fail rather than silently lose rows.
            if sales_count != raw_sales or demand_count != raw_demand:
                raise ValueError(f'Fact coverage mismatch: sales {sales_count}/{raw_sales}; demand {demand_count}/{raw_demand}. Check dimension join keys.')
    logging.info('FACT SALES %s total (%s new); DEMAND %s total (%s new)', sales_count, inserted_sales, demand_count, inserted_demand)
    return {"fact_sales":sales_count,"fact_demand":demand_count,
            "new_sales":inserted_sales,"new_demand":inserted_demand}


QUERIES = {
    "revenue_by_channel": """
        SELECT c.sales_channel, COUNT(*) AS transactions,
               ROUND(SUM(f.net_sales_usd),2) AS revenue_usd,
               ROUND(SUM(f.gross_margin_usd),2) AS gross_margin_usd
        FROM mart.fact_sales f JOIN mart.dim_channel c USING(channel_key)
        GROUP BY c.sales_channel ORDER BY revenue_usd DESC""",
    "monthly_forecast_vs_consumption": """
        SELECT d.year_number, d.month_number,
               SUM(f.forecast_demand_packs) AS forecast_packs,
               SUM(f.consumed_quantity_packs) AS consumed_packs,
               SUM(f.unfulfilled_demand_packs) AS unfulfilled_packs,
               SUM(f.stockout_days) AS stockout_days
        FROM mart.fact_demand f JOIN mart.dim_date d USING(date_key)
        GROUP BY d.year_number,d.month_number ORDER BY d.year_number,d.month_number""",
    "top_10_cold_chain_medicines": """
        SELECT m.generic_name, m.therapeutic_class,
               SUM(f.quantity_sold_packs) AS quantity_packs,
               ROUND(SUM(f.net_sales_usd),2) AS sales_usd
        FROM mart.fact_sales f JOIN mart.dim_medicine m USING(medicine_key)
        WHERE m.cold_chain_flag='Y'
        GROUP BY m.generic_name, m.therapeutic_class
        ORDER BY quantity_packs DESC LIMIT 10""",
    "sales_vs_demand_by_location": """
        WITH sales AS (
           SELECT location_key, SUM(quantity_sold_packs) AS sold_packs
           FROM mart.fact_sales GROUP BY location_key
        ), demand AS (
           SELECT location_key, SUM(consumed_quantity_packs) AS consumed_packs,
                  SUM(unfulfilled_demand_packs) AS unfulfilled_packs
           FROM mart.fact_demand GROUP BY location_key
        )
        SELECT l.city,l.state, COALESCE(s.sold_packs,0) AS sold_packs,
               COALESCE(d.consumed_packs,0) AS consumed_packs,
               COALESCE(d.unfulfilled_packs,0) AS unfulfilled_packs
        FROM mart.dim_location l
        LEFT JOIN sales s USING(location_key)
        LEFT JOIN demand d USING(location_key)
        ORDER BY l.state,l.city""",
}


def run_queries():
    with connect_db() as con:
        with con.cursor() as cur:
            for name, query in QUERIES.items():
                t0 = time.perf_counter()
                cur.execute(query)
                rows = cur.fetchall()
                elapsed_ms = round((time.perf_counter()-t0)*1000, 2)
                logging.info("QUERY %s: %.2fms, %d result rows, first: %s", name, elapsed_ms, len(rows), rows[:3])
                cur.execute("""INSERT INTO ops.query_log
                    (query_name, duration_ms, result_rows, status) VALUES (%s,%s,%s,'success')""",
                    (name, elapsed_ms, len(rows)))
    return "4 analytical queries executed and logged"


@dag(
    dag_id="sdi_phase1_etl",
    description="Incremental Postgres staging → 6 shared dimensions → sales + demand facts → analytical queries",
    schedule=None,
    start_date=pendulum.datetime(2026,11,1,tz="UTC"),
    catchup=False,
    max_active_runs=1,
    tags=["DAWH", "Phase-1", "SDI", "Postgres", "ETL"],
)
def sdi_phase1_etl():
    @task
    def initialize_database_tables():
        with connect_db() as con:
            with con.cursor() as cur:
                cur.execute(CREATE_SQL)
        return "staging, mart, and ops schemas initialized"

    @task
    def stage_master():
        return ingest("01_master_data.csv")

    @task
    def stage_sales():
        return ingest("05_pharmacy_sales_data.csv")

    @task
    def stage_demand():
        return ingest("06_hospital_demand_data.csv")

    @task
    def load_dimensions():
        return build_dimensions()

    @task
    def load_facts():
        return build_facts()

    @task
    def execute_analytics():
        return run_queries()

    ready = initialize_database_tables()
    staged = [stage_master(), stage_sales(), stage_demand()]
    dims = load_dimensions()
    facts = load_facts()
    analytics = execute_analytics()
    for stage in staged:
        ready >> stage >> dims
    dims >> facts >> analytics

sdi_phase1_etl()
